import fs from 'node:fs';
import path from 'node:path';

/**
 * Builds `src/data/speciesPhotos.ts` from the manifests produced by the
 * fetchers, plus a small table of manual corrections.
 *
 * Usage:
 *   node scripts/fetch-photos-curated.mjs   # primary pass
 *   node scripts/fetch-loose-photos.mjs     # microbe fallback (optional)
 *   node scripts/build-photo-data.mjs       # writes the TS module
 *   node scripts/build-credits-doc.mjs      # writes docs/PHOTO-CREDITS.md
 */

const MANIFESTS = ['photo-manifest.json', 'photo-loose.json'];

const LABEL = {
  cc0: 'CC0',
  'cc-by': 'CC BY',
  'cc-by-sa': 'CC BY-SA',
  'cc-by-nc': 'CC BY-NC',
  'cc-by-nc-sa': 'CC BY-NC-SA',
  'Unsplash License': 'Unsplash License',
};

/**
 * Photos that were replaced by hand after visual review. Keys are taxon names;
 * values override whatever the fetch pipeline produced.
 */
const OVERRIDES = {
  Homo_sapiens: {
    source: 'Unsplash',
    license: 'Unsplash License',
    credit: 'Unsplash',
    pageUrl: 'https://unsplash.com/photos/man-wearing-white-v-neck-shirt-3ujVzg9i2EI',
  },
  Salmonella_enterica: {
    source: 'iNaturalist',
    license: 'CC BY',
    credit: 'Volker Brinkmann, Max Planck Institute for Infection Biology',
    pageUrl: 'https://www.inaturalist.org/taxa/519551',
  },
  Staphylococcus_aureus: {
    source: 'iNaturalist',
    license: 'CC BY-SA',
    credit: 'Ajay Kumar Chaurasiya',
    pageUrl: 'https://www.inaturalist.org/taxa/486586',
  },
  Streptococcus_pyogenes: {
    source: 'iNaturalist',
    license: 'CC BY-SA',
    credit: 'Y tambe',
    pageUrl: 'https://www.inaturalist.org/taxa/130852',
  },
  Streptomyces_coelicolor: {
    source: 'iNaturalist',
    license: 'CC BY-NC',
    credit: 'Josh McGinnis',
    pageUrl: 'https://www.inaturalist.org/taxa/356564',
    caption: '链霉菌属（Streptomyces）的菌落；天蓝色链霉菌是其中研究最多的一种，属级代表照片。',
  },
};

function cleanCredit(attribution) {
  if (!attribution) return '';
  let text = attribution.trim();
  text = text.replace(/^\(c\)\s*/i, '').replace(/^©\s*/, '');
  text = text.replace(/,?\s*uploaded by .*$/i, '');
  text = text.replace(/,?\s*(some|all) rights reserved.*$/i, '');
  text = text.replace(/,\s*\(CC[^)]*\)/gi, '');
  text = text.replace(/^no rights reserved.*$/i, '');
  return text.trim();
}

const entries = new Map();
for (const manifestPath of MANIFESTS) {
  if (!fs.existsSync(manifestPath)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  for (const entry of manifest.entries ?? []) {
    if (!entry.name || entries.has(entry.name)) continue;
    if (!fs.existsSync(path.join('public', entry.file))) continue;
    entries.set(entry.name, entry);
  }
}

for (const [name, override] of Object.entries(OVERRIDES)) {
  const base = entries.get(name);
  if (!base) continue;
  entries.set(name, { ...base, ...override });
}

const sorted = [...entries.values()].sort((a, b) => a.name.localeCompare(b.name));
if (!sorted.length) {
  console.error('没有可用条目：请先运行 scripts/fetch-photos-curated.mjs');
  process.exit(1);
}

const lines = [
  `import type { TaxonPhoto } from '../types';`,
  '',
  '/**',
  ' * Representative photos for the bundled teaching species.',
  ' *',
  ' * Sources:',
  ' *  - iNaturalist (https://www.inaturalist.org): community-curated taxon',
  ' *    photos and research-grade observations under the CC license listed',
  ' *    per species.',
  ' *  - Unsplash (https://unsplash.com): the Unsplash License for the one',
  ' *    stock portrait used for Homo sapiens.',
  ' *',
  ' * Every entry keeps `pageUrl` so the attribution shown in the UI can be',
  ' * verified against the original record. Bundled images live in',
  ' * `public/species/` and are regenerated by `scripts/fetch-photos-curated.mjs`.',
  ' * Full credits: docs/PHOTO-CREDITS.md',
  ' */',
  'export const bundledPhotos: Record<string, TaxonPhoto> = {',
];

for (const entry of sorted) {
  const license = LABEL[entry.license] ?? String(entry.license).toUpperCase();
  const credit = entry.credit ?? cleanCredit(entry.attribution);
  lines.push(`  ${entry.name}: {`);
  lines.push(`    url: '${entry.file}',`);
  lines.push(`    source: '${entry.source ?? 'iNaturalist'}',`);
  lines.push(`    license: '${license}',`);
  if (credit) lines.push(`    credit: ${JSON.stringify(credit)},`);
  lines.push(`    pageUrl: '${entry.pageUrl}',`);
  if (entry.caption) lines.push(`    caption: ${JSON.stringify(entry.caption)},`);
  lines.push('  },');
}

lines.push('};', '', 'export function photoFor(taxon: string): TaxonPhoto | undefined {');
lines.push('  return bundledPhotos[taxon];', '}', '');

fs.writeFileSync('src/data/speciesPhotos.ts', lines.join('\n'));
console.log(`wrote ${sorted.length} species to src/data/speciesPhotos.ts`);
